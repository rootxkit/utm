export type Lang = "en" | "ka";
export type Translate = (key: Key, values?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
  return (key, values) => {
    const template = (lang === "ka" ? ka[key] : undefined) ?? en[key];
    return values
      ? template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""))
      : template;
  };
}

export const I18n = createContext<{ lang: Lang; t: Translate }>({
  lang: "en",
  t: translator("en"),
});

export const useI18n = () => useContext(I18n);
export const useT = () => useContext(I18n).t;
